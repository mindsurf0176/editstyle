// Run with Playwright installed. Uses the real local app and FFmpeg, no UI mocks.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}, acceptDownloads: true});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.EDITSTYLE_URL || 'http://127.0.0.1:18470');
  await page.getByRole('button', {name: 'cinematic 프리셋'}).waitFor();
  await page.screenshot({path: 'out/companion-empty.png', fullPage: true});
  await page.getByRole('button', {name: '새 스타일 작성'}).click();
  await page.locator('#style-document').fill('# QA 관찰형\n> EDITSTYLE v1\n## Rhythm\n- 반응이 끝날 때까지 장면을 유지합니다.\n## Subtitles\n- 설명용 자막만 사용합니다.');
  await page.getByRole('button', {name: '내 스타일로 저장'}).click();
  await page.locator('#style-dialog').waitFor({state: 'hidden'});
  assert.equal(await page.locator('#style-name').innerText(), 'QA 관찰형');
  await page.locator('#video-file').setInputFiles(path.resolve('out/style-comparison/source.mp4'));
  await page.waitForFunction(() => document.getElementById('notice').textContent.includes('영상 준비가 끝났어요'), {timeout: 180000});
  assert.equal(await page.locator('#frames img').count(), 8);
  await page.getByRole('button', {name: '컷 직접 작성', exact: true}).click();
  await page.locator('#clip-rows tr').first().waitFor();
  while (await page.locator('#clip-rows tr').count() > 2) await page.getByRole('button', {name: '이 컷 삭제'}).last().click();
  const rows = page.locator('#clip-rows tr');
  await rows.nth(0).locator('[data-field=start]').fill('0');
  await rows.nth(0).locator('[data-field=end]').fill('1');
  await rows.nth(0).locator('[data-field=caption]').fill('잠깐의 평온');
  await rows.nth(1).locator('[data-field=start]').fill('3');
  await rows.nth(1).locator('[data-field=end]').fill('7');
  await rows.nth(1).locator('[data-field=caption]').fill('어디로 가는 걸까');
  assert.equal(await page.locator('#export-plan').isDisabled(), true);
  await page.getByRole('button', {name: '변경사항 저장'}).click();
  await page.waitForFunction(() => document.getElementById('dirty-indicator').textContent === '저장됨');
  await page.getByRole('button', {name: '가져오기 묶음 만들기'}).click();
  await page.locator('#export-result').waitFor({state: 'visible', timeout: 180000});
  await page.locator('#result-video').evaluate(v => v.play());
  await page.waitForFunction(() => document.getElementById('result-video').currentTime > 0.1);
  await page.locator('#result-video').evaluate(v => v.pause());
  const duration = await page.locator('#result-video').evaluate(v => v.duration);
  assert(Math.abs(duration - 5) < 0.1, `Unexpected preview duration ${duration}`);
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', {name: 'ZIP 다운로드 ↓'}).click();
  const download = await downloading;
  await download.saveAs(path.resolve('out/companion-browser.zip'));
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path: 'out/companion-desktop.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: 'out/companion-mobile.png', fullPage: true});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.setViewportSize({width: 1440, height: 1000});
  await page.getByRole('button', {name: '모델 연결'}).click();
  await page.locator('#model-name').fill('missing-test-model');
  await page.getByRole('button', {name: '연결 확인', exact: true}).click();
  await page.locator('#model-error').waitFor({state: 'visible', timeout: 150000});
  await page.locator('#model-dialog .close-dialog').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#style-name').textContent === 'QA 관찰형');
  assert.equal(await page.locator('#source-name').innerText(), 'source.mp4');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({passed: true, previewSeconds: duration, browserErrors: errors, screenshots: ['out/companion-desktop.png','out/companion-mobile.png']}));
  await browser.close();
})().catch(error => {console.error(error); process.exit(1);});
